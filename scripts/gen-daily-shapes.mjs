// Generates src/styles/dailyReportShapes.css: the folder-tab / section-shoulder / dialog-shoulder silhouettes of the
// Daily Report as SVG data-URIs, used through border-image (9-slice: the curved shoulders keep their shape, the flat
// middle stretches with the text). Colours are baked into the SVG, so each tint is its own custom property.
//   node scripts/gen-daily-shapes.mjs
import { writeFileSync } from 'node:fs';

const svg = (inner) => `<svg xmlns='http://www.w3.org/2000/svg' width='100' height='60' viewBox='0 0 100 60' preserveAspectRatio='none'>${inner}</svg>`;
const url = (s) => `url("data:image/svg+xml,${encodeURIComponent(s)}")`;

// main tab: slanted shoulders, flat top, flared feet that merge into the layer below
const TAB = 'M0 60 C9 60 11 55 14 46 C17 35 19 13 32 9 L68 9 C81 13 83 35 86 46 C89 55 91 60 100 60';
const tab = (top, bot, rim) => url(svg(
  `<defs><linearGradient id='g' x1='0' y1='0' x2='0' y2='1'><stop offset='0' stop-color='${top}'/><stop offset='1' stop-color='${bot}'/></linearGradient></defs>` +
  `<path d='${TAB} Z' fill='url(#g)'/><path d='${TAB}' fill='none' stroke='${rim}' stroke-width='1' vector-effect='non-scaling-stroke'/>`));

// nested-sheet shoulder: round left corner, slanted right side that sinks into the band
const SEC = 'M0 60 L0 18 C0 10 5 5 13 5 L72 5 C79 5 82 9 85 19 C88 33 92 52 100 56';
const sec = (top, bot, rim) => url(svg(
  `<defs><linearGradient id='g' x1='0' y1='0' x2='0' y2='1'><stop offset='0' stop-color='${top}'/><stop offset='1' stop-color='${bot}'/></linearGradient></defs>` +
  `<path d='${SEC} L100 60 Z' fill='url(#g)'/><path d='${SEC}' fill='none' stroke='${rim}' stroke-width='1' vector-effect='non-scaling-stroke'/>`));

const tabs = {
  active: tab('#F1DAFB', '#E4C9F4', '#C28BD6'),
  t1: tab('#D9D0F4', '#C5B9E9', '#A99AD6'),   // Weekly: blue-lavender
  t2: tab('#D8D6FB', '#C6C3F0', '#A9A6DF'),   // Monthly: periwinkle
  t3: tab('#E0D0E6', '#D1BDD9', '#B79FC2'),   // Annual: dusty rose
  t4: tab('#EAD6FB', '#DDC1F1', '#C28BD6'),   // Compare: pale violet
};
const css = `/* GENERATED by scripts/gen-daily-shapes.mjs — do not edit by hand. */
.daily-report-design {
${Object.entries(tabs).map(([k, v]) => `  --shape-tab-${k}: ${v};`).join('\n')}
  --shape-section: ${sec('#FFFFFF', '#FDFBFF', '#DCC8EA')};
  --shape-dialog: ${sec('#F2E1FA', '#EAD3F6', '#D2B0E3')};
}
.tmodal-overlay.daily-report-design {
  --shape-dialog: ${sec('#F2E1FA', '#EAD3F6', '#D2B0E3')};
}
`;
writeFileSync(new URL('../src/styles/dailyReportShapes.css', import.meta.url), css);
console.log('written', css.length, 'bytes');
