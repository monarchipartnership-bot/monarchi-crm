// Appended by code (not the AI) so the exact text is guaranteed, per the doc.
export const EMAIL_SIGNATURE = `Sincerely,
Arthur and the Mon'Archi team.
Our website: https://www.monarchi.agency/uk/`;

export function appendSignatureIfEmail(messageText, format) {
  if (format !== 'email') return messageText;
  return `${messageText}\n\n${EMAIL_SIGNATURE}`;
}

const FIXED_STYLE_BLOCK = `ФІКСОВАНИЙ СТИЛЬ НАПИСАННЯ (обов'язково дотримуватись):
- Тон: дружній, живий, неформальний (friendly, creative, informal).
- Уникай нав'язливого чи шаблонного тону.
- Уникай фраз "I can help", "I can provide", "provide", "You have an interesting task" і подібних (та їхніх аналогів мовою листа).
- КАТЕГОРИЧНО заборонено використовувати шаблонні фрази на кшталт "I hope you're doing well", "I hope this message finds you well", "Сподіваюсь, у вас все добре" і будь-які їхні аналоги мовою листа. Замість цього — жива пряма ПИТАННЯ про справи (див. пункт 1 структури нижче).
- Не копіюй і не дублюй дослівні фрази клієнта з діалогу.
- Уникай зайвої пунктуації: дужки (), тире -, знаки оклику !.`;

function formatInstructionBlock(format) {
  if (format === 'email') {
    return `ФОРМАТ: EMAIL-РОЗСИЛКА.
- Додай коротку тему листа (subject line), яка природно відображає суть повідомлення, без клікбейту.
- Лист починається зі звернення на кшталт "Dear [Ім'я]," / "Доброго дня, [Ім'я]," (адаптуй мовою листа).
- Текст листа оформи природними абзацами.
- НЕ пиши сам жодного закриття/підпису листа (жодного "Sincerely", "З повагою" тощо) — фіксований підпис буде додано окремо автоматично.`;
  }
  return `ФОРМАТ: UPWORK ЧАТ.
- Пиши як коротке особисте повідомлення в чаті, без теми листа, без формального звернення "Dear", без підпису в кінці.`;
}

function oldLeadStructureBlock(format, language) {
  const emailAddendum = format === 'email'
    ? ' Для email ОБОВ\'ЯЗКОВО прямо вкажи, що спілкування відбувалось на Upwork — почни цю частину з фрази на кшталт "Раніше ми спілкувались з вами на Upwork про..." і продовж конкретною суттю розмови.'
    : '';
  return `ОБОВ'ЯЗКОВА СТРУКТУРА ПОВІДОМЛЕННЯ (рівно 4 частини, у цьому порядку):
1. Повідомлення ОБОВ'ЯЗКОВО починається з прямого ПИТАННЯ про справи клієнта — наприклад "Як справи?", "Як ваші успіхи?", "How's it going?", "How have things been?" (адаптуй під мову листа: ${language}). Це має бути справжнє питання зі знаком питання, а не ствердження на кшталт "I hope you're doing well" — так писати заборонено.
2. Нагадування про те, про що говорили раніше. Можна почати з фрази на кшталт "Раніше ми спілкувались з вами про..." (адаптуй мовою листа). Уважно проаналізуй саме повідомлення КЛІЄНТА (не свої власні) — якщо клієнт давав посилання на свій сайт чи проєкт, визнач і згадай назву цього проєкту.${emailAddendum}
3. Інформація про наші успіхи за цей час. Можна почати з фрази на кшталт "До речі, за цей час у нас був цікавий проєкт, в якому..." (адаптуй мовою листа), і далі — релевантний кейс/результат.
4. Конкретна пропозиція обговорити нові можливості чи задачі — активне запрошення, а не пасивне очікування. Наприклад, запропонуй коротку 15-хвилинну розмову і поясни, чим вона буде корисна саме клієнту (розібрати нові ідеї, подивитись на поточні результати, обговорити наступні кроки тощо). Повідомлення ОБОВ'ЯЗКОВО завершується справжнім питанням зі знаком питання (наприклад, чи зручно клієнту коротко поговорити цього тижня, чи цікаво обговорити конкретну ідею) — а не констатацією на кшталт "якщо колись знадобиться допомога, звертайтесь".`;
}

