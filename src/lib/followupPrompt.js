// Appends already-generated earlier steps (if any) as context, so a later
// step doesn't literally repeat them, and explicitly names which case each
// one used so FU4 can reliably avoid repeating FU1's case (rule 4 above).
export function appendPreviousStepsContext(userMessage, previousMessages) {
  if (!previousMessages || !previousMessages.length) return userMessage;
  const block = previousMessages.map((p) => {
    const caseNote = p.caseUsed ? ` (використаний кейс: ${p.caseUsed})` : '';
    return `FU${p.step}${caseNote}:\n${p.message}`;
  }).join('\n\n');
  return `${userMessage}\n\nПопередні кроки серії, вже надіслані клієнту (не повторюй їх дослівно, стиль чи кейс):\n${block}`;
}

export function buildUserMessage({ chat, nameOverride, projectsBlock, extraContext }) {
  return `Діалог з клієнтом:
"""
${chat}
"""

${nameOverride ? "Ім'я клієнта (уточнено користувачем): " + nameOverride : ''}

Доступні кейси (проєкти Monarchi):
${projectsBlock}

${extraContext ? "Додатковий контекст від користувача (обов'язково врахуй):\n" + extraContext : ''}`;
}

// Splits the model's raw reply into the header block (ДАТА/ТОН/ХІД РОЗМОВИ/
// ІМ'Я/СУТЬ/КЕЙС) and the actual follow-up message text.
export function parseOldLeadReply(fullText) {
  const parts = fullText.split('---');
  let headerPart = parts[0] || '';
  let messagePart = parts.slice(1).join('---').trim();

  if (!messagePart) {
    messagePart = fullText.trim();
    headerPart = '';
  }

  const dateMatch = headerPart.match(/ДАТА:\s*(.+)/);
  const toneMatch = headerPart.match(/ТОН:\s*(.+)/);
  const flowMatch = headerPart.match(/ХІД РОЗМОВИ:\s*(.+)/);
  const nameMatch = headerPart.match(/ІМ'Я:\s*(.+)/);
  const essenceMatch = headerPart.match(/СУТЬ:\s*(.+)/);
  const caseMatch = headerPart.match(/КЕЙС:\s*(.+)/);

  return {
    messagePart,
    date: dateMatch?.[1]?.trim() ?? null,
    tone: toneMatch?.[1]?.trim() ?? null,
    flow: flowMatch?.[1]?.trim() ?? null,
    name: nameMatch?.[1]?.trim() ?? null,
    essence: essenceMatch?.[1]?.trim() ?? null,
    caseUsed: caseMatch?.[1]?.trim() ?? null,
  };
}

// Splits a single series-step reply into its КЕЙС header and message body.
export function parseSeriesStepReply(fullText) {
  const parts = fullText.split('---');
  let headerPart = parts[0] || '';
  let messagePart = parts.slice(1).join('---').trim();

  if (!messagePart) {
    messagePart = fullText.trim();
    headerPart = '';
  }

  const caseMatch = headerPart.match(/КЕЙС:\s*(.+)/);

  return {
    message: messagePart,
    caseUsed: caseMatch?.[1]?.trim() ?? null,
  };
}
