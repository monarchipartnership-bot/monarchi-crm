// ISO 3166-1 alpha-2 codes with Ukrainian names, used by the deal "Країна"
// field. Flags render via the `flag-icons` package's SVGs (see the `fi fi-xx`
// class built by `flagClass`) rather than the flag emoji — Windows' bundled
// emoji font has no flag glyphs at all and just shows the two-letter
// regional-indicator code as literal text, so relying on the emoji font
// would leave every Windows user seeing "UA" instead of a flag.
import 'flag-icons/css/flag-icons.min.css';

export function flagClass(code) {
  return 'fi fi-' + (code || '').toLowerCase();
}

