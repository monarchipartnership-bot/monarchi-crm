CPM (Cost Per Mille) — вартість за 1000 показів
Формула: CPM = (Витрати на рекламу / Кількість показів) × 1000
Q: Коли варто оптимізувати саме під CPM, а не під CPC чи CPA? CPM важливий для іміджевих (awareness) кампаній, де мета — максимальне охоплення за мінімальну вартість, а не негайні кліки чи продажі. Для перформанс-кампаній фокус завжди на CPA/ROAS, а CPM — лише проміжний індикатор.

ROAS (Return on Ad Spend) — окупність рекламних витрат
Формула: ROAS = Дохід від реклами / Витрати на рекламу
Приклад: витрачено 10 000 грн на рекламу, отримано дохід 50 000 грн → ROAS = 5 (кожна вкладена гривня принесла 5 гривень доходу)
Бенчмарк: для e-commerce мінімально прийнятний ROAS зазвичай 3-4, з урахуванням собівартості товару, логістики й інших витрат. "Хороший" ROAS сильно залежить від маржинальності ніші.
Q: ROAS = 5, це точно прибутково? Не обов'язково! ROAS рахує лише дохід відносно витрат на рекламу — він не враховує собівартість товару, логістику, оплату персоналу, повернення товару. Компанія з низькою маржею (наприклад, 15%) може мати "красивий" ROAS = 5, але фактично працювати в збиток, якщо не врахувати всі витрати. Для реальної прибутковості дивіться ROI.
Зв'язок: ROAS — це "сирий" показник ефективності реклами, ROI — повна картина бізнесу.

ROI (Return on Investment) — повернення інвестицій
Формула: ROI = ((Дохід - Загальні витрати) / Загальні витрати) × 100%
Приклад: дохід 50 000 грн, загальні витрати (реклама + собівартість + логістика + зарплати) — 35 000 грн → ROI = ((50 000-35 000)/35 000) × 100% = 42.9%
Q: У чому головна різниця між ROI і ROAS? ROAS враховує тільки рекламний бюджет. ROI враховує всі витрати бізнесу — виробництво, логістику, зарплати, оренду тощо. ROAS показує ефективність саме реклами, ROI показує прибутковість бізнесу в цілому. Клієнту завжди варто пояснювати обидва показники разом, бо високий ROAS не гарантує позитивного ROI.

