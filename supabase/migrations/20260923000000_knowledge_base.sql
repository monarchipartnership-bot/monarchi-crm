CPA (Cost Per Action/Acquisition) — вартість дії
Формула: CPA = Загальні витрати на рекламу / Кількість конверсій
Приклад: витрачено 20 000 грн, отримано 40 конверсій → CPA = 500 грн
Q: Як зрозуміти, чи CPA прийнятний? Порівняйте CPA з середнім чеком (AOV) і маржинальністю продукту. Якщо CPA = 500 грн, а прибуток з одного замовлення (не виручка, а саме прибуток) — 700 грн, кампанія прибуткова. Якщо прибуток 300 грн — кампанія збиткова, навіть якщо продажі є.

CPL (Cost Per Lead) — вартість ліда
Формула: CPL = Витрати на рекламу / Кількість лідів
Q: Чим CPL відрізняється від CPA? CPL рахує вартість "потенційного клієнта" (заявка, дзвінок, заповнена форма) — це проміжний етап. CPA рахує вартість фінальної цільової дії (найчастіше — продажу). Один лід ще не гарантує продажу, тому CPL завжди варто аналізувати разом з Lead-to-Customer Rate (яка частка лідів стає реальними клієнтами).

