-- source docs in Monarchi Bot's knowledge_docs/ — content preserved as-is,
-- only split into topic-sized articles so it can be browsed, searched and
-- edited one section at a time instead of as one giant blob per category).

create table if not exists kb_categories (
  id bigint generated always as identity primary key,
  key text not null unique,
  label text not null,
  color text not null default '#6B2FA0',
  position int not null default 1,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists kb_articles (
  id bigint generated always as identity primary key,
  category_id bigint not null references kb_categories(id) on delete cascade,
  title text not null,
  content text not null default '',
  position int not null default 1,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists kb_articles_category_idx on kb_articles(category_id);

alter table kb_categories enable row level security;
drop policy if exists kb_categories_select on kb_categories;
create policy kb_categories_select on kb_categories for select using (true);
drop policy if exists kb_categories_insert on kb_categories;
create policy kb_categories_insert on kb_categories for insert with check (auth.role() = 'authenticated');
drop policy if exists kb_categories_update on kb_categories;
create policy kb_categories_update on kb_categories for update using (auth.role() = 'authenticated');
drop policy if exists kb_categories_delete on kb_categories;
create policy kb_categories_delete on kb_categories for delete using (auth.role() = 'authenticated');

alter table kb_articles enable row level security;
drop policy if exists kb_articles_select on kb_articles;
create policy kb_articles_select on kb_articles for select using (true);
drop policy if exists kb_articles_insert on kb_articles;
create policy kb_articles_insert on kb_articles for insert with check (auth.role() = 'authenticated');
drop policy if exists kb_articles_update on kb_articles;
create policy kb_articles_update on kb_articles for update using (auth.role() = 'authenticated');
drop policy if exists kb_articles_delete on kb_articles;
create policy kb_articles_delete on kb_articles for delete using (auth.role() = 'authenticated');

